#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")" && pwd)"
MODE="apply"

case "${1:-}" in
  "")
    MODE="apply"
    ;;
  --dry-run|-n)
    MODE="dry-run"
    ;;
  --check|-c)
    MODE="check"
    ;;
  --help|-h)
    cat <<'EOF'
Usage: ./link.sh [--dry-run | --check]

Symlink repository config files into ~/.config/ (file-level symlinks only)
and generate ~/.config/ghostty/local-paths.conf with machine-local $HOME paths.

Options:
  (default)       Idempotently create symlinks (backs up existing files first)
  --dry-run, -n   Preview all actions without modifying disk
  --check, -c     Verify every symlink & generated local-paths.conf (healthy / missing / broken / replaced)
EOF
    exit 0
    ;;
  *)
    echo "Unknown option: $1" >&2
    exit 2
    ;;
esac

# Mapping: "<repo-relative-src>:<~/.config-relative-dst>"
LINKS=(
  "herdr/config.toml:herdr/config.toml"
  "herdr/cheatsheet.py:herdr/cheatsheet.py"
  "ghostty/config:ghostty/config"
  "ghostty/shaders/herdr-focus-glow.glsl:ghostty/shaders/herdr-focus-glow.glsl"
  "wallpaper/base-bg.jpg:ghostty/assets/backdrop.jpg"
)

LOCAL_PATHS_FILE="${HOME}/.config/ghostty/local-paths.conf"
EXPECTED_LOCAL_PATHS="$(cat <<EOF
# Auto-generated by link.sh — machine-local paths (not tracked in git)
background-image = ${HOME}/.config/ghostty/assets/backdrop.jpg
custom-shader = ${HOME}/.config/ghostty/shaders/herdr-focus-glow.glsl
EOF
)"

TS="$(date +%Y%m%d-%H%M%S)"
FAILED=0

for entry in "${LINKS[@]}"; do
  src_rel="${entry%%:*}"
  dst_rel="${entry#*:}"
  src="${ROOT_DIR}/${src_rel}"
  dst="${HOME}/.config/${dst_rel}"

  if [[ ! -e "$src" ]]; then
    echo "[ERR     ] source missing in repo: $src"
    FAILED=1
    continue
  fi

  if [[ "$MODE" == "check" ]]; then
    if [[ -L "$dst" ]]; then
      target="$(readlink "$dst")"
      if [[ ! -e "$dst" ]]; then
        echo "[BROKEN  ] $dst -> $target (target does not exist)"
        FAILED=1
      elif [[ "$target" == "$src" ]]; then
        echo "[OK      ] $dst -> $src"
      else
        echo "[WRONG   ] $dst -> $target (expected $src)"
        FAILED=1
      fi
    elif [[ -e "$dst" ]]; then
      echo "[REPLACED] $dst is a regular file (symlink was overwritten!)"
      FAILED=1
    else
      echo "[MISSING ] $dst"
      FAILED=1
    fi
    continue
  fi

  # apply or dry-run
  if [[ -L "$dst" && "$(readlink "$dst")" == "$src" ]]; then
    echo "[SKIP] already linked: $dst -> $src"
    continue
  fi

  parent="$(dirname "$dst")"
  if [[ ! -d "$parent" ]]; then
    if [[ "$MODE" == "dry-run" ]]; then
      echo "[DRY ] mkdir -p $parent"
    else
      mkdir -p "$parent"
    fi
  fi

  if [[ -L "$dst" || -e "$dst" ]]; then
    backup="${dst}.bak-${TS}"
    if [[ "$MODE" == "dry-run" ]]; then
      echo "[DRY ] mv $dst -> $backup"
    else
      mv "$dst" "$backup"
      echo "[BAK ] $dst -> $backup"
    fi
  fi

  if [[ "$MODE" == "dry-run" ]]; then
    echo "[DRY ] ln -s $src $dst"
  else
    ln -s "$src" "$dst"
    echo "[LINK] $dst -> $src"
  fi
done

# Manage ~/.config/ghostty/local-paths.conf (machine-local absolute paths for Ghostty)
if [[ "$MODE" == "check" ]]; then
  if [[ ! -f "$LOCAL_PATHS_FILE" ]]; then
    echo "[MISSING ] $LOCAL_PATHS_FILE (run ./link.sh to generate)"
    FAILED=1
  elif [[ "$(cat "$LOCAL_PATHS_FILE")" == "$EXPECTED_LOCAL_PATHS" ]]; then
    echo "[OK      ] $LOCAL_PATHS_FILE (matches \$HOME)"
  else
    echo "[STALE   ] $LOCAL_PATHS_FILE differs from expected \$HOME paths"
    FAILED=1
  fi
else
  if [[ -f "$LOCAL_PATHS_FILE" && "$(cat "$LOCAL_PATHS_FILE")" == "$EXPECTED_LOCAL_PATHS" ]]; then
    echo "[SKIP] up to date: $LOCAL_PATHS_FILE"
  elif [[ "$MODE" == "dry-run" ]]; then
    echo "[DRY ] write $LOCAL_PATHS_FILE"
  else
    mkdir -p "$(dirname "$LOCAL_PATHS_FILE")"
    printf '%s\n' "$EXPECTED_LOCAL_PATHS" > "$LOCAL_PATHS_FILE"
    echo "[GEN ] $LOCAL_PATHS_FILE"
  fi
fi

if [[ "$MODE" == "check" ]]; then
  if [[ "$FAILED" -ne 0 ]]; then
    echo "Check failed: one or more links need attention. Run ./link.sh to repair."
    exit 1
  fi
  echo "All ${#LINKS[@]} symlinks and local-paths.conf are healthy."
fi
